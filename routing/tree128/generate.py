"""Generate both consumers from pinned semantic and path-local lowering artifacts.

python -m routing.tree128.generate [--engine /path/to/Stockfish]
The semantic SHA is independent of lowering/layout SHA. No analysis imports.
"""

import argparse
import hashlib
import json
from pathlib import Path

from . import IDENTITY, ROOT, SPEC, TABLE_HASH


def field(i):
    return f"c.get({i})"


def member(i, values):
    values = sorted(values)
    size = SPEC["raw_features"][i]["size"]
    v = field(i)
    if not values:
        return "false"
    if len(values) == size:
        return "true"
    if len(values) == 1:
        return f"({v} == {values[0]})"
    if values == list(range(values[0], values[-1] + 1)):
        return f"({values[0]} <= {v} && {v} <= {values[-1]})"
    return f"((0x{sum(1 << x for x in values):x}u >> {v}) & 1u)"


def expression(e):
    op = e["op"]
    if op == "member":
        return member(e["field"], e["values"])
    if op in ("and", "or", "bool_equal"):
        symbol = {"and": "&&", "or": "||", "bool_equal": "=="}[op]
        return f"({expression(e['left'])} {symbol} {expression(e['right'])})"
    a, b = map(field, e["fields"])
    r, k = e["relation"], e["threshold"]
    return {
        "ne": lambda: f"({a} != {b})",
        "sum": lambda: f"({a} + {b} <= {k})",
        "difference": lambda: f"({a} - {b} <= {k})",
        "absolute_difference": lambda: f"(std::abs({a} - {b}) <= {k})",
    }[r]()


def generate():
    manifests = [
        json.loads((ROOT / n).read_text())
        for n in ("artifact_hashes.json", "lowering_hashes.json")
    ]
    for manifest in manifests:
        for name, digest in manifest.items():
            if (ROOT / name).exists() and hashlib.sha256(
                (ROOT / name).read_bytes()
            ).hexdigest() != digest:
                raise ValueError(f"artifact digest mismatch: {name}")
    out = [
        "// Generated by routing/tree128/generate.py; do not edit.",
        "#pragma once",
        "#include <cstdlib>",
        "#include <cstdint>",
        "namespace frozen_tree128 {",
        f'inline constexpr char Identity[] = "{IDENTITY}";',
        f"inline constexpr std::uint32_t TableHash = 0x{TABLE_HASH:08x}u;",
        "inline constexpr unsigned char Digest[32] = {"
        + ",".join(str(x) for x in bytes.fromhex(IDENTITY))
        + "};",
    ]
    rules = json.loads((ROOT / "binary_routing.json").read_text())
    assert rules["source_routing_sha256"] == IDENTITY
    out += [
        "template<class Context> inline int select(const Context& c) {",
        f"goto n{rules['root']};",
    ]
    for node in rules["nodes"]:
        out.append(f"n{node['id']}:")
        if node["kind"] == "leaf":
            out.append(f"return {node['leaf_id']};")
        else:
            assert node["kind"] == "binary"
            out.append(
                f"if ({expression(node['condition'])}) goto n{node['yes']}; else goto n{node['no']};"
            )
    out += ["}", "}"]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", type=Path)
    args = ap.parse_args()
    trainer = ROOT.parents[1]
    data = generate().encode()
    (trainer / "data_loader/cpp/tree128_generated.h").write_bytes(data)
    if args.engine:
        (args.engine / "src/nnue/tree128_generated.h").write_bytes(data)
        (args.engine / "src/nnue/tree128_context.h").write_bytes(
            (ROOT / "context.h").read_bytes()
        )
    (ROOT / "implementation_hashes.json").write_text(
        json.dumps(
            {
                "semantic_sha256": IDENTITY,
                "generated_sha256": hashlib.sha256(data).hexdigest(),
                "context_sha256": hashlib.sha256(
                    (ROOT / "context.h").read_bytes()
                ).hexdigest(),
            },
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
